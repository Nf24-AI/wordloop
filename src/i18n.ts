/** Arabic counting: 1, 2, 3–10, 11+ */
function arCount(n:number,one:string,two:string,few:string,many:string,zero?:string){
  if(n===0&&zero)return zero;
  return n===1?one:n===2?two:n>=3&&n<=10?`${n} ${few}`:`${n} ${many}`;
}
